type Variables = Record<string, string | number>;

interface LanguageContextValue {
  language: Language;
  locale: string;
  setLanguage: (language: Language) => void;
  toggleLanguage: () => void;
  t: (key: TranslationKey, variables?: Variables) => string;
}

const LanguageContext = createContext<LanguageContextValue | null>(null);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<Language>("en");

  useEffect(() => {
    document.documentElement.lang = language === "en" ? "en" : "zh-CN";
  }, [language]);

  const value = useMemo<LanguageContextValue>(() => {
    const messages = language === "en" ? en : zh;
    return {
      language,
      locale: language === "en" ? "en-US" : "zh-CN",
      setLanguage,
      toggleLanguage: () => setLanguage((current) => (current === "en" ? "zh" : "en")),
      t: (key, variables) => {
        let message: string = messages[key];
        for (const [name, replacement] of Object.entries(variables ?? {})) {
          message = message.replaceAll(`{${name}}`, String(replacement));
        }
        return message;
      },
    };
  }, [language]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

// The provider and hook intentionally share this small context module.
// eslint-disable-next-line react-refresh/only-export-components
export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error("useLanguage must be used within LanguageProvider");
  }
  return context;
}
